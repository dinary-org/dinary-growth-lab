import json
import subprocess
from pathlib import Path

from dgl.analysis import media
from dgl.qc.video_qc import run_qc
from dgl.render.build import chunk_caption, srt_ts, write_srt

ROOT = Path(__file__).resolve().parents[1]


def test_probe_and_cut_detection(tiny_video):
    meta = media.probe(tiny_video)
    assert (meta["width"], meta["height"]) == (1080, 1920) and meta["has_audio"]
    cuts = media.scene_cuts(tiny_video, media.EDIT_THRESHOLD)
    assert len(cuts) == 1 and abs(cuts[0] - 1.5) < 0.05


def test_analyze_file_records_access_level_and_evidence(tiny_video, tmp_path):
    rec = media.analyze_file(tiny_video, tmp_path / "ev", rights_basis="test fixture generated by ffmpeg")
    assert rec["access_level"] == "full_av"
    assert rec["features"]["n_shots"] == 2
    assert all(Path(f["path"]).exists() for f in rec["frames"])
    assert rec["transcript"]["source"] in ("none", "whisper_local")


def test_analyze_requires_rights_basis(tiny_video, tmp_path):
    import pytest
    with pytest.raises(ValueError):
        media.analyze_file(tiny_video, tmp_path, rights_basis="")


def test_qc_flags_missing_subtitles_and_loudness(tiny_video):
    qc = run_qc(tiny_video, None, expected_duration=3)
    failed = {c["check"] for c in qc["checks"] if not c["pass"]}
    assert not qc["pass"]
    assert "subtitle_sidecar" in failed and "loudness_integrated" in failed
    assert "resolution" not in failed and "aspect_9_16" not in failed


def test_qc_detects_black_frames_and_wrong_aspect(tmp_path):
    out = tmp_path / "bad.mp4"
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", "color=c=black:s=1280x720:d=2:r=30",
                    "-c:v", "libx264", "-pix_fmt", "yuv420p", str(out)], check=True)
    failed = {c["check"] for c in run_qc(out, None)["checks"] if not c["pass"]}
    assert {"resolution", "aspect_9_16", "black_frames", "audio_present"} <= failed


def test_srt_roundtrip(tmp_path):
    caps = [{"start": 0.0, "end": 1.25, "text": "안녕하세요"}, {"start": 61.5, "end": 62.0, "text": "끝"}]
    p = write_srt(caps, tmp_path / "x.srt")
    assert media.read_srt(p) == caps
    assert srt_ts(3661.007) == "01:01:01,007"
    assert all(len(c) <= 16 for c in chunk_caption("양치하면서 세수하고 세수하면서 옷까지 입기 그리고 출근"))


def test_committed_render_passed_qc():
    qc = json.loads((ROOT / "outputs" / "videos" / "c_20261031_snooze_loop.qc.json").read_text())
    assert qc["pass"] and qc["media"]["width"] == 1080 and qc["media"]["height"] == 1920
